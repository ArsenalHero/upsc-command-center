import originals from "./pyq-bank.json";
import polity from "./polity-bank.json";
import geography from "./geography-bank.json";
import additional from "./additional-bank.json";
import historyEconomy from "./history-economy-bank.json";
import ancientCulture from "./ancient-culture-bank.json";
import duplicates from "./duplicate-groups.json";
import reviews from "./explanation-reviews.json";
import suppliedMatches from "./supplied-explanation-matches.json";
import { englishQuestion } from "../utils/englishQuestion";
import type { ExplanationReview, PYQQuestion } from "../utils/pyq";
import { buildQuestionCollections } from "../utils/questionCollections";

export const originalBank = originals as PYQQuestion[];
export const polityBank = polity as PYQQuestion[];
export const geographyBank = geography as PYQQuestion[];
export const additionalBank = additional as PYQQuestion[];
export const historyEconomyBank = historyEconomy as PYQQuestion[];
export const ancientCultureBank = ancientCulture as PYQQuestion[];
export const rawQuestionBank = [...originalBank, ...polityBank, ...geographyBank, ...additionalBank, ...historyEconomyBank, ...ancientCultureBank];
const collections = buildQuestionCollections(rawQuestionBank, duplicates, reviews as Record<string, ExplanationReview>);
export const questionBank = collections.questions.map(q => englishQuestion(q, suppliedMatches));
export const questionById = new Map([...collections.byId].map(([id, q]) => [id, englishQuestion(q, suppliedMatches)]));
for (const q of questionBank) questionById.set(q.id, q);
export const canonicalQuestionId = collections.canonicalId;
export const canonicalRecords = collections.canonicalRecords;
export const latestBankAttempts = collections.latest;
