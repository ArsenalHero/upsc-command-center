export function createEmptyData(): AppData {
  const today = dateKey();
  const subjects: Subject[] = master.map(([name, stage, paper], i) => ({
    id: `subject-${i}`,
    name,
    stage,
    paper,
    color: COLORS[i % COLORS.length],
    priority: stage === "CSAT" ? 4 : 3,
    targetAllocation: stage === "Optional" ? 20 : stage === "CSAT" ? 10 : 5,
  }));
  const topics: Topic[] = master.flatMap(([, , , names], i) =>
    names.map((name, j) => ({
      id: `topic-${i}-${j}`,
      subjectId: `subject-${i}`,
      parentId: null,
      name,
      status: "Not Started" as const,
      revisionStage: "New topic" as const,
      notes: "",
      importance: 3,
      createdAt: today,
      statusHistory: [{ date: today, status: "Not Started" as const }],
    })),
  );
  topics.push(
    ...[
      "Lok Sabha",
      "Rajya Sabha",
      "Parliamentary Committees",
      "Anti-Defection",
    ].map((name, i) => ({
      id: `parliament-${i}`,
      subjectId: "subject-3",
      parentId: "topic-3-4",
      name,
      status: "Not Started" as const,
      revisionStage: "New topic" as const,
      notes: "",
      importance: 4,
      createdAt: today,
      statusHistory: [{ date: today, status: "Not Started" as const }],
    })),
  );
  for (let p = 0; p < 2; p++)
    for (let u = 0; u < 4; u++) {
      const id = `optional-${p}-${u}`;
      topics.push({
        id,
        subjectId: "subject-13",
        parentId: `topic-13-${p}`,
        name: `Unit ${u + 1}`,
        status: "Not Started",
        revisionStage: "New topic",
        notes: "",
        importance: 3,
        createdAt: today,
        statusHistory: [{ date: today, status: "Not Started" }],
      });
      topics.push({
        id: id + "-topic",
        subjectId: "subject-13",
        parentId: id,
        name: `Topic ${u + 1}`,
        status: "Not Started",
        revisionStage: "New topic",
        notes: "",
        importance: 3,
        createdAt: today,
        statusHistory: [{ date: today, status: "Not Started" }],
      });
    }
  return {
    schemaVersion: 1,
    settings: {
      ...defaultSettings,
      allocation: { ...defaultSettings.allocation },
      weights: { ...defaultSettings.weights },
    },
    subjects,
    topics,
    sessions: [],
    mcqs: [],
    tests: [],
    answers: [],
    essays: [],
    ethics: [],
    currentAffairs: [],
    pyqs: [],
    revisions: [],
    resources: [],
    catalog: [],
    goals: [
      {
        id: "goal-hours",
        name: "Daily study",
        metric: "Hours",
        target: 8,
        period: "Daily",
        subjectId: "",
      },
      {
        id: "goal-mcq",
        name: "Daily MCQs",
        metric: "MCQs",
        target: 50,
        period: "Daily",
        subjectId: "",
      },
      {
        id: "goal-answer",
        name: "Weekly answers",
        metric: "Answers",
        target: 14,
        period: "Weekly",
        subjectId: "",
      },
      {
        id: "goal-revision",
        name: "Monthly revisions",
        metric: "Revision",
        target: 20,
        period: "Monthly",
        subjectId: "",
      },
    ],
  };
}
