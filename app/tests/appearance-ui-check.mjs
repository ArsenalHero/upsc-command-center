assert.equal(w.document.documentElement.style.getPropertyValue("--wallpaper-image"), "none");
assert.equal(w.document.querySelector('dialog [aria-label="Wallpaper visibility"]'), null);
assert.equal(w.document.querySelector('dialog a[download]'), null);
await clickText("Reset appearance");
