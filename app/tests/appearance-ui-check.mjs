assert.equal(stored().settings.theme, "light");
assert.equal(stored().settings.dailyHours, 6.5);
assert.equal(errors.length, 0, errors.join("\n"));
w.close();
console.log("Appearance checks passed: five palettes, four landscapes, immediate saving, device mode, tuning, download, daily rotation, dialog focus, unsaved target preservation, reload and reset.");
