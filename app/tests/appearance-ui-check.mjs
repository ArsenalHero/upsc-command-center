import { build } from "esbuild";
import { JSDOM, VirtualConsole } from "jsdom";
import assert from "node:assert/strict";

const built = await build({ entryPoints: ["src/main.tsx"], bundle: true, write: false, format: "iife", platform: "browser", target: "es2022", loader: { ".css": "empty" }, define: { "import.meta.env": JSON.stringify({ PROD: false }) }, jsx: "automatic" });
const errors = [];
const vc = new VirtualConsole();
vc.on("jsdomError", error => { if (!String(error).includes("navigation")) errors.push(String(error)); });
const wait = () => new Promise(resolve => setTimeout(resolve, 60));
const until = async (predicate, message) => { for (let n = 0; n < 80; n++) { if (predicate()) return; await wait(); } assert.ok(predicate(), message); };
function createWindow(saved) {
  const dom = new JSDOM('<html><body><div id="root"></div></body></html>', { url: "https://example.test/upsc/#/", runScripts: "outside-only", pretendToBeVisual: true, virtualConsole: vc });
  const w = dom.window;
  const listeners = new Set();
  const media = { matches: false, addEventListener(event, fn) { listeners.add(fn); }, removeEventListener(event, fn) { listeners.delete(fn); } };
  w.matchMedia = () => media;
  w.setDarkDevice = value => { media.matches = value; listeners.forEach(fn => fn({ matches: value })); };
  w.structuredClone = globalThis.structuredClone;
  w.scrollTo = () => {};
  w.fetch = async () => ({ ok: true, json: async () => ({ url: "", publishableKey: "" }) });
  w.ResizeObserver = class { observe() {} unobserve() {} disconnect() {} };
  w.HTMLDialogElement.prototype.showModal = function () { this.setAttribute("open", ""); };
  w.HTMLDialogElement.prototype.close = function () { this.removeAttribute("open"); };
  if (saved) w.localStorage.setItem("upsc-command-center:v1", saved);
  w.eval(built.outputFiles[0].text);
  return w;
}
let w = createWindow();
const click = async selector => { const el = w.document.querySelector(selector); assert.ok(el, `Missing ${selector}`); el.focus(); el.click(); await wait(); };
const clickText = async value => { const el = [...w.document.querySelectorAll("button")].find(el => el.textContent.trim() === value); assert.ok(el, `Missing ${value}`); el.focus(); el.click(); await wait(); };
const change = async (el, value) => { const setter = Object.getOwnPropertyDescriptor(w.HTMLInputElement.prototype, "value").set; setter.call(el, value); el.dispatchEvent(new w.Event("input", { bubbles: true })); el.dispatchEvent(new w.Event("change", { bubbles: true })); await wait(); };
const stored = () => JSON.parse(w.localStorage.getItem("upsc-command-center:v1"));
await until(() => w.document.querySelector("h1"), "Login not rendered");
await clickText("Continue as guest");
await until(() => w.document.body.textContent.includes("Set up your preparation workspace"), "Guest setup not rendered");
await clickText("Skip setup");
await click('[aria-label="Open themes and wallpapers"]');
assert.ok(w.document.querySelector("dialog[open]"));
assert.equal(w.document.querySelectorAll("dialog .appearance-palette").length, 5);
assert.equal(w.document.querySelectorAll("dialog .wallpaper-choice").length, 6);
await click('dialog [aria-label="Forest theme"]');
await click('dialog [aria-label="Mountain dawn wallpaper"]');
assert.equal(w.document.documentElement.dataset.palette, "forest");
assert.equal(w.document.documentElement.dataset.wallpaper, "mountains");
assert.equal(stored().settings.appearance.palette, "forest");
assert.match(w.document.documentElement.style.getPropertyValue("--wallpaper-image"), /https:\/\/example.test\/upsc\/wallpapers\/mountain-dawn.webp/);
await change(w.document.querySelector('dialog [aria-label="Wallpaper visibility"]'), "55");
await change(w.document.querySelector('dialog [aria-label="Wallpaper blur"]'), "7");
assert.equal(stored().settings.appearance.visibility, 55);
assert.equal(w.document.documentElement.style.getPropertyValue("--wallpaper-blur"), "7px");
const download = w.document.querySelector('dialog a[download]');
assert.match(download.href, /mountain-dawn.webp$/);
assert.equal(download.download, "mountains-landscape.webp");
await click('dialog input[value="system"]');
w.setDarkDevice(true); await wait();
assert.equal(w.document.documentElement.dataset.theme, "dark");
assert.match(w.document.querySelector("dialog .appearance-preview").getAttribute("aria-label"), /dark mode/);
w.setDarkDevice(false); await wait();
assert.equal(w.document.documentElement.dataset.theme, "light");
await click('dialog [aria-label="Rotate landscape daily"]');
assert.equal(stored().settings.appearance.wallpaper, "daily");
assert.ok(["mountains", "forest", "coast", "meadows"].includes(w.document.documentElement.dataset.wallpaper));
await click('dialog [aria-label="Close dialog"]');
assert.equal(w.document.querySelector("dialog[open]"), null);
assert.equal(w.document.activeElement.getAttribute("aria-label"), "Open themes and wallpapers");
w.location.hash = "/settings";
await until(() => w.document.querySelector("h1")?.textContent === "Preparation settings", "Settings not rendered");
await wait();
const target = w.document.querySelector('[aria-label="Daily study hours"]');
await change(target, "6.5");
assert.match(w.document.querySelector(".settings-change-status").textContent, /Unsaved/, "Target edit did not reach React state");
await click('[aria-label="Violet theme"]');
await click('[aria-label="Forest lake wallpaper"]');
await click('.theme-options input[value="dark"]');
assert.equal(w.document.querySelector('[aria-label="Daily study hours"]').value, "6.5", "Appearance changes erased an unsaved target");
assert.match(w.document.querySelector(".settings-change-status").textContent, /Unsaved/);
assert.equal(stored().settings.dailyHours, 8, "Appearance must not save a preparation draft");
await clickText("Save settings");
assert.equal(stored().settings.dailyHours, 6.5);
assert.equal(stored().settings.appearance.palette, "violet");
assert.equal(stored().settings.appearance.wallpaper, "forest");
assert.equal(stored().settings.theme, "dark");
const saved = w.localStorage.getItem("upsc-command-center:v1");
w.close(); w = createWindow(saved);
await until(() => w.document.querySelector("h1"), "Reload not rendered");
if ([...w.document.querySelectorAll("button")].some(el => el.textContent.trim() === "Continue as guest")) await clickText("Continue as guest");
await until(() => w.document.querySelector('[aria-label="Open themes and wallpapers"]'), "Reloaded workspace not rendered");
assert.equal(w.document.documentElement.dataset.palette, "violet");
assert.equal(w.document.documentElement.dataset.wallpaper, "forest");
assert.equal(w.document.documentElement.dataset.theme, "dark");
assert.equal(stored().settings.dailyHours, 6.5);
await click('[aria-label="Open themes and wallpapers"]');
await click('dialog [aria-label="Plain background"]');
