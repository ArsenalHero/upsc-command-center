import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { prepareMockDatabase, setMockUser, fixtureLicense } from "./mock-license-fixture";
import { aurumAccuracy } from "../src/utils/aurum";

const question = (id: string, subject = "Polity") => ({ origin: "pyq", sourceId: id, sourceLabel: "Reviewed PYQ", question: `Saved question ${id}: which choice is correct?`,
  subject, topic: "Foundations", options: { a: "First", b: "Second", c: "Third", d: "Fourth" }, correct: "a", explanation: "The first option follows from the premise." });
test("Aurum reports and flags persist across visits, backfill old sets, isolate owners and preserve scoring/exclusions", async () => {
  const db = new PGlite(), owner = "11111111-1111-4111-8111-111111111111", other = "22222222-2222-4222-8222-222222222222";
  const api = async (op: string, p: any = {}) => (await db.query<{data:any}>("select public.mock_lab($1,$2::jsonb) data", [op,JSON.stringify(p)])).rows[0].data;
  try {
    await prepareMockDatabase(db,[{id:owner},{id:other}]);
    for(const file of ["20261104031926_aurum_subject_practice.sql","20261104045009_aurum_fast_setup.sql","20261104060906_aurum_subject_choices.sql"]) await db.exec(readFileSync(new URL(`../supabase/migrations/${file}`,import.meta.url),"utf8"));
    await setMockUser(db,owner); await api("verify-license",{licenseKey:fixtureLicense});
    const old=await api("aurum-start",{requestId:crypto.randomUUID(),source:"pyq",subjects:["Polity","Geography"],count:3,questions:[question("old-1"),question("old-2","Geography"),question("old-3")]});
    await api("aurum-answer",{sessionId:old.id,questionId:old.questions[0].id,option:"a"});
    await api("aurum-answer",{sessionId:old.id,questionId:old.questions[1].id,option:"b"});
    const completed=await api("aurum-finish",{sessionId:old.id});
    await db.exec("reset role");
    const migration=readFileSync(new URL("../supabase/migrations/20261104165754_aurum_analysis_review.sql",import.meta.url),"utf8");
    await db.exec(migration); await setMockUser(db,owner);
    const analysis=await api("aurum-analysis");
    assert.deepEqual(analysis.overall,{total:3,answered:3,correct:1,incorrect:1,skipped:1,flagged:0});
    assert.equal(aurumAccuracy(analysis.overall),50); assert.equal(aurumAccuracy({correct:0,incorrect:0}),null);
    assert.equal(analysis.completedSets,1); assert.equal(analysis.subjects.length,2);
    const history=await api("aurum-history"); assert.equal(history.total,1); assert.equal(history.items[0].id,old.id);
    assert.equal(Object.hasOwn(history.items[0],"questions"),false); assert.equal(Object.hasOwn(history.items[0],"answers"),false);
    const wrong=await api("aurum-review",{filter:"incorrect"});
    assert.equal(wrong.total,1); assert.equal(wrong.items[0].questionId,old.questions[1].id);
    for(const key of ["options","correct","explanation","answers"]) assert.equal(Object.hasOwn(wrong.items[0],key),false);
    const saved=await api("aurum-flag",{sessionId:old.id,questionId:old.questions[1].id,flagged:true});
    assert.deepEqual(saved.flags,[old.questions[1].id]); assert.equal(Object.hasOwn(saved,"questions"),false);
    await api("aurum-flag",{sessionId:old.id,questionId:old.questions[1].id,flagged:true});
    assert.equal((await api("aurum-review",{filter:"flagged"})).total,1,"Explicit repeated flag saves are idempotent");
    assert.equal((await api("aurum-analysis")).overall.flagged,1);
    assert.equal((await api("aurum-history")).items[0].flagged,1);
    const reopened=await api("aurum-session",{sessionId:old.id});
    assert.deepEqual(reopened.answers,completed.answers); assert.deepEqual(reopened.summary,completed.summary);
    assert.deepEqual(reopened.flags,[old.questions[1].id]);
    assert.equal((await api("aurum-review",{filter:"incorrect",subject:"Polity"})).total,0);
    assert.equal((await api("aurum-review",{filter:"incorrect",search:"old-2",source:"pyq"})).total,1);
    await assert.rejects(api("aurum-flag",{sessionId:old.id,questionId:"not-a-question",flagged:true}),/Question not found/);
    await assert.rejects(api("aurum-flag",{sessionId:old.id,questionId:old.questions[0].id,flagged:"true"}),/flag state/);
    await assert.rejects(api("aurum-review",{filter:"invalid"}),/valid review filters/);
    await assert.rejects(db.query("select * from mock_private.aurum_question_progress"),/permission denied/);
    await assert.rejects(db.query("select mock_private.aurum_review_api('aurum-analysis','{}',$1)",[other]),/permission denied/);
    await setMockUser(db,other); await assert.rejects(api("aurum-analysis"),/License/); await api("verify-license",{licenseKey:fixtureLicense});
    assert.equal((await api("aurum-history")).total,0); assert.equal((await api("aurum-review",{filter:"all"})).total,0);
    assert.equal((await api("aurum-analysis")).overall.total,0);
    await assert.rejects(api("aurum-flag",{sessionId:old.id,questionId:old.questions[1].id,flagged:false,userId:owner}),/not found/);
    await setMockUser(db,owner);
    const next=await api("aurum-start",{requestId:crypto.randomUUID(),source:"pyq",subjects:["Polity"],count:2,questions:[question("new-1"),question("new-2")]});
    await api("aurum-flag",{sessionId:next.id,questionId:next.questions[0].id,flagged:true});
    const redacted=await api("aurum-session",{sessionId:next.id});
    assert.equal(redacted.questions[0].correct,undefined,"Flagging never reveals unchecked keys");
    await api("aurum-answer",{sessionId:next.id,questionId:next.questions[0].id,option:"a"});
    const partial=await api("aurum-analysis");
    assert.equal(partial.runningSets,1); assert.equal(partial.overall.total,5); assert.equal(partial.overall.answered,4);
    assert.equal((await api("aurum-session",{sessionId:next.id})).flags.includes(next.questions[0].id),true,"Answer sync preserves an existing flag");
    await api("aurum-answer",{sessionId:next.id,questionId:next.questions[1].id,option:"b"});
    const total=await api("aurum-analysis"); assert.deepEqual(total.overall,{total:5,answered:5,correct:2,incorrect:2,skipped:1,flagged:2});
    const page1=await api("aurum-history",{limit:1}), page2=await api("aurum-history",{limit:1,offset:1});
    assert.equal(page1.total,2); assert.equal(page1.items.length,1); assert.notEqual(page1.items[0].id,page2.items[0].id);
    const qp1=await api("aurum-review",{filter:"all",limit:2}), qp2=await api("aurum-review",{filter:"all",limit:2,offset:2});
    assert.equal(qp1.total,5); assert.equal(new Set([...qp1.items,...qp2.items].map((q:any)=>q.questionId)).size,4);
    await db.exec("reset role"); await db.exec(migration); await setMockUser(db,owner);
    assert.equal((await api("aurum-analysis")).overall.flagged,2,"Migration replay keeps saved flags");
    await api("aurum-flag",{sessionId:old.id,questionId:old.questions[1].id,flagged:false});
    assert.equal((await api("aurum-review",{filter:"flagged"})).total,1);
    assert.equal((await api("aurum-state")).practised,5);
    await assert.rejects(api("aurum-start",{requestId:crypto.randomUUID(),source:"pyq",subjects:["Polity"],count:1,questions:[question("old-1")]}),/already used/);
    await setMockUser(db,null);
    const guestToken="a".repeat(64),secondToken="b".repeat(64);
    await api("verify-license",{guestToken,licenseKey:fixtureLicense});
    const guest=await api("aurum-start",{guestToken,requestId:crypto.randomUUID(),source:"pyq",subjects:["Polity"],count:1,questions:[question("guest")]});
    await api("aurum-answer",{guestToken,sessionId:guest.id,questionId:guest.questions[0].id,option:"b"});
    await api("aurum-flag",{guestToken,sessionId:guest.id,questionId:guest.questions[0].id,flagged:true});
    assert.equal((await api("aurum-review",{guestToken,filter:"flagged"})).total,1);
    await api("verify-license",{guestToken:secondToken,licenseKey:fixtureLicense});
    assert.equal((await api("aurum-analysis",{guestToken:secondToken})).overall.total,0);
    await assert.rejects(api("aurum-flag",{guestToken:secondToken,sessionId:guest.id,questionId:guest.questions[0].id,flagged:false}),/not found/);
    await assert.rejects(api("aurum-history"),/Sign in/);
  } finally { await db.close(); }
});
